import type { Test } from "./schema";

/** Build a Code Mode program body. Test data stays in `values`, not in the program text. */
export function compileLaya(test: Pick<Test, "id" | "url" | "steps">): string {
  return [
    `// Code Mode program for ${JSON.stringify(test.id)}. Edit for this run only.`,
    `// Inputs are supplied as values.url and values.steps; browser operations run in the Laya MCP sandbox.`,
    `const stepResults = [];`,
    `let runError = null;`,
    `let recording = await browser.videos({});`,
    `if (!recording.videos_dir) return { passed: false, stepResults: [], error: "Laya Browser video recording is not configured", recording };`,
    `if (!recording.videos.some(video => video.status === "recording")) recording = await browser.startRecording({});`,
    `if (!recording.videos.some(video => video.status === "recording")) return { passed: false, stepResults: [], error: "Could not start Laya Browser video recording", recording };`,
    `await browser.open({ url: values.url });`,
    `for (const step of values.steps) {`,
    `  let status = "passed";`,
    `  let error;`,
    `  try {`,
    `    if (step.type === "act") {`,
    `      await browser.do({ goal: step.text, values: step.data ? { data: step.data } : undefined });`,
    `      if (step.expected) {`,
    `        const check = await browser.check({ question: "Verify this expected result is already true; do not change the page: " + step.expected });`,
    `        if (check.p_yes < 0.85) { status = "failed"; error = "Expected result was not verified (confidence " + check.p_yes + ")"; }`,
    `      }`,
    `    } else if (step.type === "assert") {`,
    `      const check = await browser.check({ question: step.text });`,
    `      if (check.p_yes < 0.85) { status = "failed"; error = "Assertion was not verified (confidence " + check.p_yes + ")"; }`,
    `    } else if (step.type === "expect") {`,
    `      const expected = step.value || step.text;`,
    `      if (step.target === "url") {`,
    `        const tabs = await browser.listTabs();`,
    `        const active = tabs.tabs.find(tab => tab.active) || tabs.tabs[0];`,
    `        if (!active?.url.includes(expected)) { status = "failed"; error = "URL does not include " + expected; }`,
    `      } else {`,
    `        const page = await browser.snapshot({ max_chars: 20000 });`,
    `        if (!page.text.includes(expected)) { status = "failed"; error = "Visible text not found: " + expected; }`,
    `      }`,
    `    }`,
    `  } catch (cause) {`,
    `    status = "failed"; error = String(cause); runError = error;`,
    `  }`,
    `  stepResults.push({ stepId: step.id, text: step.text, status, ...(error ? { error } : {}) });`,
    `  if (status !== "passed") break;`,
    `}`,
    `for (const step of values.steps.slice(stepResults.length)) stepResults.push({ stepId: step.id, text: step.text, status: "skipped" });`,
    `recording = await browser.stopRecording({});`,
    `if (!recording.videos.some(video => video.status === "completed")) return { passed: false, stepResults, error: "Laya Browser video recording did not finalize", recording };`,
    `return { passed: stepResults.length === values.steps.length && stepResults.every(step => step.status === "passed"), stepResults, error: runError, finalUrl: (await browser.listTabs()).tabs.find(tab => tab.active)?.url || null, recording };`,
    ``,
  ].join("\n");
}
